<?php

declare(strict_types=1);

/**
 * หน้าแรกของเว็บคือแดชบอร์ด — ไฟล์นี้มีไว้เพื่อให้ URL ราก ("/") ไปถึงมัน
 *
 * ใช้ require ไม่ใช่ redirect หรือ DirectoryIndex ใน .htaccess เพราะ:
 *   * redirect ทำให้หน้าแรกเสียเวลาไปหนึ่ง round trip ทุกครั้งฟรี ๆ
 *   * DirectoryIndex ต้องพึ่ง AllowOverride ของโฮสต์ ถ้าปิดอยู่ หน้าแรกจะตาย
 *     ทั้งหน้า ต่างจาก /api ที่ยังมีทางเรียก /api/index.php/... ตรง ๆ ได้
 * ส่วน index.php เป็นชื่อที่เว็บเซิร์ฟเวอร์ทุกตัวหาให้เองอยู่แล้วโดยไม่ต้องตั้งอะไร
 *
 * ลิงก์ภายในทุกที่ชี้มาที่ url('/') เพื่อให้ "/" เป็น URL หลักของหน้านี้
 * (dashboard.php เปิดตรงก็ได้ผลเหมือนกัน)
 */

// ก่อนหน้านี้ "/" คือหน้ารายการรุ่นรถ ลิงก์ที่ถูกบุ๊กมาร์ก/แชร์ไว้จึงมีคำค้นกับเลขหน้า
// ติดมาด้วย (เช่น /?q=yaris&page=2) ส่งต่อไป models.php พร้อม query เดิม
// ดีกว่าปล่อยให้ตกมาที่แดชบอร์ดแล้วคำค้นหายไปเงียบ ๆ
//
// ใช้ 302 ไม่ใช่ 301 เพราะ 301 ถูกเบราว์เซอร์แคชค้างไว้ยาว แก้ทีหลังแล้วตามถอนไม่ได้
if (isset($_GET['q']) || isset($_GET['page'])) {
    require_once __DIR__ . '/lib/asset.php';

    header('Location: ' . url('/models.php') . '?' . http_build_query($_GET));
    exit;
}

require __DIR__ . '/dashboard.php';
